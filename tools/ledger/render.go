// buildSummary computes all roll-up data from the operations and work packages.
func buildSummary(in *inputs, ops []parityOp, wsDoc *webSocketDoc) summaryData {
	s := summaryData{
		TagCounts:       make(map[string]statusCounts),
		SubsystemCounts: make(map[string]statusCounts),
	}

	// Swiftfin count.
	swiftfinOps := filterSwiftfin(ops)
	s.SwiftfinTotal = len(swiftfinOps)
	for _, op := range swiftfinOps {
		if op.Status == "done" {
			s.SwiftfinDone++
		}
	}
	if s.SwiftfinTotal > 0 {
		s.SwiftfinPercent = float64(s.SwiftfinDone) / float64(s.SwiftfinTotal) * 100
	}
	// Swiftfin conveniences (non-REST): SDK features that Swiftfin uses but
	// that do not appear as Paths.* operations. They are not counted in the
	// REST parity fraction. docs/03-api-surface.md:11-16 defines this set.
	s.SwiftfinConveniences = []string{
		"POST /Users/AuthenticateByName — login by username and password",
		"POST /Users/AuthenticateWithQuickConnect — login by QuickConnect code",
		"POST /QuickConnect/Initiate — start a QuickConnect authorization",
		"GET /QuickConnect/Connect — poll a QuickConnect secret",
		"GET /socket — WebSocket transport for real-time session and playback control",
		"UDP :7359 discovery — auto-discovery broadcast for local Jellyfin servers",
	}

	// Tag and subsystem counts.
	for _, op := range ops {
		subsystem := op.Subsystem
		if op.Shadow {
			// Shadow ops use their own subsystem from shadow-spec.
			subsystem = op.Subsystem
		}
		sc := s.TagCounts[subsystem]
		sc.Total++
		addStatus(&sc, op.Status)
		s.TagCounts[subsystem] = sc

		// Also track subsystem counts for shadow ops separately.
		if op.Shadow {
			ssc := s.SubsystemCounts[op.Subsystem]
			ssc.Total++
			addStatus(&ssc, op.Status)
			s.SubsystemCounts[op.Subsystem] = ssc
		}
	}

	// Unimplemented list.
	for _, op := range ops {
		if op.Status == "todo" || op.Status == "partial" || op.Status == "stubbed" || op.Status == "deferred" {
			s.Unimplemented = append(s.Unimplemented, unimplRow{
				Subsystem: op.Subsystem,
				ID:        op.ID,
				Status:    op.Status,
				Reason:    op.Reason,
			})
		}
	}
	sort.Slice(s.Unimplemented, func(i, j int) bool {
		if s.Unimplemented[i].Subsystem != s.Unimplemented[j].Subsystem {
			return s.Unimplemented[i].Subsystem < s.Unimplemented[j].Subsystem
		}
		return s.Unimplemented[i].ID < s.Unimplemented[j].ID
	})

	// WebSocket count.
	s.WebSocketDone = wsDoc.Source.ImplementedCount
	s.WebSocketTotal = wsDoc.Source.UpstreamCount

	// Shadow coverage.
	shadowTotal := 0
	shadowRegistered := 0
	for _, op := range ops {
		if op.Shadow {
			shadowTotal++
			if op.Registered {
				shadowRegistered++
			}
		}
	}
	s.ShadowCoverage = shadowCoverage{
		Total:      shadowTotal,
		Registered: shadowRegistered,
	}

	return s
}

func addStatus(sc *statusCounts, status string) {
	switch status {
	case "done":
		sc.Done++
	case "partial":
		sc.Partial++
	case "stubbed":
		sc.Stubbed++
	case "deferred":
		sc.Deferred++
	case "todo":
		sc.Todo++
	}
}

// renderMarkdown renders the PARITY.md file.
func renderMarkdown(l *ledger) string {
	var b strings.Builder

	// Header.
	b.WriteString("# Parity Ledger\n\n")
	b.WriteString("This file is generated by `tools/ledger`. Do not edit it directly.\n")
	b.WriteString("Edit `ledger/annotations.yaml` and `ledger/shadow-spec.yaml`, then run `make ledger`.\n\n")

	// Source metadata.
	b.WriteString("## Source\n\n")
	fmt.Fprintf(&b, "- Deadfin revision: `%s`\n", l.Parity.Source.DeadfinRevision)
	fmt.Fprintf(&b, "- Jellyfin pin: `%s`\n", l.Parity.Source.JellyfinPin)
	fmt.Fprintf(&b, "- Route count: %d\n", l.Parity.Source.RouteCount)
	fmt.Fprintf(&b, "- OpenAPI version: %s\n\n", l.Parity.Source.OpenAPIVersion)

	// Phase progress is not rendered (D16, 2026-09-01). The work-package
	// Status: lines stopped being maintained when the plan moved to forge
	// issues and release trains; a table built from them reported phases as
	// "todo" while the release that shipped them was in production.

	// Swiftfin REST fraction.
	b.WriteString("## Swiftfin REST parity\n\n")
	fmt.Fprintf(&b, "- Done: %d / %d\n", l.Summary.SwiftfinDone, l.Summary.SwiftfinTotal)
	fmt.Fprintf(&b, "- Percentage: %.1f%%\n\n", l.Summary.SwiftfinPercent)

	// Swiftfin convenience summary.
	b.WriteString("## Swiftfin conveniences (non-REST)\n\n")
	b.WriteString("These SDK conveniences are not counted in the REST parity fraction:\n\n")
	for _, c := range l.Summary.SwiftfinConveniences {
		fmt.Fprintf(&b, "- %s\n", c)
	}
	b.WriteString("\n")

	// Counts by tag/subsystem.
	b.WriteString("## Counts by subsystem\n\n")
	b.WriteString("| Subsystem | Done | Partial | Stubbed | Deferred | Todo | Total |\n")
	b.WriteString("|---|---|---|---|---|---|---|\n")

	// Collect and sort subsystem names.
	var subsystems []string
	for sub := range l.Summary.TagCounts {
		subsystems = append(subsystems, sub)
	}
	sort.Strings(subsystems)

	for _, sub := range subsystems {
		sc := l.Summary.TagCounts[sub]
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d |\n",
			sub, sc.Done, sc.Partial, sc.Stubbed, sc.Deferred, sc.Todo, sc.Total)
	}
	b.WriteString("\n")

	// Unimplemented list.
	b.WriteString("## Unimplemented operations\n\n")
	if len(l.Summary.Unimplemented) == 0 {
		b.WriteString("None.\n\n")
	} else {
		var currentSub string
		for _, row := range l.Summary.Unimplemented {
			if row.Subsystem != currentSub {
				if currentSub != "" {
					b.WriteString("\n")
				}
				fmt.Fprintf(&b, "### %s\n\n", row.Subsystem)
				b.WriteString("| Operation | Status | Reason |\n")
				b.WriteString("|---|---|---|\n")
				currentSub = row.Subsystem
			}
			reason := row.Reason
			if reason == "" {
				reason = "—"
			}
			fmt.Fprintf(&b, "| %s | %s | %s |\n", row.ID, row.Status, reason)
		}
		b.WriteString("\n")
	}

	// WebSocket count.
	b.WriteString("## WebSocket\n\n")
	fmt.Fprintf(&b, "- Implemented: %d / %d\n", l.Summary.WebSocketDone, l.Summary.WebSocketTotal)
	b.WriteString("\n")

	// Shadow coverage.
	b.WriteString("## Shadow coverage\n\n")
	fmt.Fprintf(&b, "- Total shadow routes: %d\n", l.Summary.ShadowCoverage.Total)
	fmt.Fprintf(&b, "- Registered: %d\n", l.Summary.ShadowCoverage.Registered)
	b.WriteString("\n")

	// Deferred-stubbed cohort.
	b.WriteString("## Deferred-stubbed cohort\n\n")
	b.WriteString("LiveTv (38 ops) and SyncPlay (22 ops) are registered as intentional stubs.\n")
	b.WriteString("They use `status: stubbed` with `disposition: deferred` per decision D2.\n\n")

	// Input diagnostics.
	b.WriteString("## Input diagnostics\n\n")
	fmt.Fprintf(&b, "- OpenAPI operations: %d\n", l.Summary.Diagnostics.OpenAPICount)
	fmt.Fprintf(&b, "- Shadow routes: %d\n", l.Summary.Diagnostics.ShadowCount)
	fmt.Fprintf(&b, "- Route snapshot routes: %d\n", l.Summary.Diagnostics.RouteCount)
	fmt.Fprintf(&b, "- Native routes (excluded from parity): %d\n", l.Summary.Diagnostics.NativeRoutes)
	fmt.Fprintf(&b, "- Duplicate operation IDs: %d\n", l.Summary.Diagnostics.DuplicateIDs)
	fmt.Fprintf(&b, "- Unknown exported routes: %d\n", l.Summary.Diagnostics.UnknownRoutes)
	fmt.Fprintf(&b, "- Unknown result operations: %d\n", l.Summary.Diagnostics.UnknownResults)
	fmt.Fprintf(&b, "- Method or path mismatches: %d\n", l.Summary.Diagnostics.MethodMismatches+l.Summary.Diagnostics.PathMismatches)

	return b.String()
}
